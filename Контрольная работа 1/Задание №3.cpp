
/**
 * Программа вычисляет значение упрощённого выражения: y^2 - 12y + 19
 * Коэффициент y вводится пользователем с клавиатуры.
 *
 * Исходное выражение (вариант): 2y(8y-5) - 15(y²-1) + 2(2-y)
 * Оно было предварительно упрощено до y^2 - 12y + 19.
 */

#include <iostream>   // Для ввода/вывода (cin, cout)
#include <iomanip>   // Для форматирования вывода (setprecision)

// Используем стандартное пространство имён для удобства чтения
using namespace std;

int main() {
    // Устанавливаем локаль для корректного отображения кириллицы в консоли (для Windows)
    #ifdef _WIN32
        system("chcp 65001 > nul");
    #endif

    // Объявляем переменную для хранения коэффициента y.
    // Используем double, чтобы поддерживать дробные значения.
    double y;

    // Выводим приглашение к вводу.
    cout << "Введите значение коэффициента y: ";

    // Считываем значение y с клавиатуры.
    if (!(cin >> y)) {
        // Если ввод некорректен (например, пользователь ввёл буквы вместо числа),
        // выводим сообщение об ошибке и завершаем программу.
        cerr << "Ошибка: введено некорректное значение. Пожалуйста, введите число." << endl;
        return 1;
    }

    // Вычисляем значение упрощённого выражения: y^2 - 12y + 19
    // Для возведения в квадрат используем умножение y * y (это быстрее и понятнее, чем pow(y, 2)).
    double result = y * y - 12.0 * y + 19.0;

    // Подготавливаем вывод результата.
    // Фиксируем точность вывода до 4 знаков после запятой для наглядности.
    cout << fixed << setprecision(4);

    // Выводим итоговое значение выражения.
    cout << "Значение выражения при y = " << y << " равно: " << result << endl;

    return 0;
}