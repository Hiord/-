// Проверка: хватит ли days дней, если разброс внутри дня не больше limit
bool enoughDays(const vector<int>& cal, int days, int limit) {
    int usedDays = 1;
    int dayStart = 0;
    for (int i = 1; i < (int)cal.size(); ++i) {
        if (cal[i] - cal[dayStart] > limit) {
            usedDays++;
            dayStart = i;
        }
    }
    return usedDays <= days;
}

void solveTask2() {
    cout << "--- Задача №2: Пирожки Арсена ---" << endl;

    int N = 5; // Количество пирожков (пример для теста)
    int D = 2; // Количество дней
    
    // Пример калорийности (можно заменить на ввод)
    vector<int> calories = {1, 5, 10, 15, 20};

    /*
    // Ввод с клавиатуры
    cout << "Введите N (кол-во пирожков) и D (кол-во дней): ";
    cin >> N >> D;
    calories.resize(N);
    cout << "Введите калорийность пирожков: ";
    for(int i=0; i<N; ++i) cin >> calories[i];
    */

    if (D > N) {
        cout << "Ошибка: дней больше, чем пирожков." << endl;
        return;
    }

    // 1. Сортируем пирожки по калорийности
    sort(calories.begin(), calories.end());

    if (D == 1) {
        cout << "Разница: " << calories[N-1] - calories[0] << endl;
        return;
    }

    // Бинарный поиск по ответу
    int low = 0, high = calories[N-1] - calories[0];
    while (low < high) {
        int mid = low + (high - low) / 2;
        if (enoughDays(calories, D, mid)) {
            high = mid;
        } else {
            low = mid + 1;
        }
    }

    cout << "Минимальная возможная максимальная разница в калориях за день: " << low << endl;
    cout << endl;
}

