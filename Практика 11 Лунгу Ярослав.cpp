void solveTask3() {
    cout << "--- Задача №3: Букет Павлика ---" << endl;

    int N = 7;
    int K = 5;
    int L = 2;
    
    // Стоимость растений
    vector<int> costs = {10, 5, 10, 20, 5, 10, 15};
    
    /*
    // Ввод с клавиатуры
    cout << "Введите N, K, L: ";
    cin >> N >> K >> L;
    costs.resize(N);
    cout << "Введите стоимости: ";
    for(int i=0; i<N; ++i) cin >> costs[i];
    */

    if (K > N) {
        cout << "Ошибка: нельзя собрать букет из K растений, если доступно меньше." << endl;
        return;
    }

    // Стратегия:
    // Чтобы максимизировать сумму, нам выгодно брать самые дорогие растения.
    // Ограничение: не более L одинаковых растений.
    // "Одинаковые растения" определяются их стоимостью (так как в массиве даны стоимости, 
    // и сказано "N различных растений", но потом "не может выбрать более L одинаковых".
    // Обычно в таких задачах под "одинаковыми" подразумеваются растения с одинаковой стоимостью.
    // Если бы растения были уникальными объектами, ограничение "L одинаковых" не имело бы смысла, 
    // если только у них нет атрибута "тип". Здесь атрибут - стоимость.
    
    // 1. Сортируем стоимости по убыванию.
    sort(costs.rbegin(), costs.rend());

    // 2. Проходим по отсортированному списку и берем растения, пока не наберем K штук,
    // соблюдая правило: для каждой стоимости можно взять не более L штук.
    
    long long total_cost = 0;
    int plants_taken = 0;
    
    // Так как список отсортирован, одинаковые стоимости идут подряд.
    // Нам нужно просто считать, сколько раз мы встретили текущую стоимость.
    
    int i = 0;
    while (plants_taken < K && i < N) {
        int current_cost = costs[i];
        int count_current = 0;
        
        // Считаем, сколько растений с такой же стоимостью доступно подряд (или вообще в массиве)
        // Но так как мы идем по сортированному массиву, мы просто берем блок одинаковых.
        
        // Находим конец блока одинаковых элементов
        int j = i;
        while (j < N && costs[j] == current_cost) {
            j++;
        }
        int available_same = j - i;
        
        // Сколько мы можем взять из этого блока?
        int take = min(available_same, L);
        
        // Но также мы не можем взять больше, чем осталось до K
        int remaining_needed = K - plants_taken;
        take = min(take, remaining_needed);
        
        total_cost += (long long)take * current_cost;
        plants_taken += take;
        
        i = j; // Переходим к следующей группе стоимостей
    }
    
    if (plants_taken < K) {
         // Теоретически невозможно при корректных входных данных, если N >= K
         cout << "Не удалось собрать полный букет." << endl;
    } else {
        cout << "Максимальная стоимость букета: " << total_cost << endl;
    }
    
    cout << endl;
}

