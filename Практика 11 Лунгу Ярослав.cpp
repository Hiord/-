void solveTask1() {
    cout << "--- Задача №1: Балльно-рейтинговая система ---" << endl;
    
    // Пример из условия:
    // 2 -3 2 3
    // 10 2 2 2
    // -3 20 2 2
    
    int N = 3; // Строки
    int M = 4; // Столбцы
    
    // Можно раскомментировать ввод с клавиатуры, если нужно тестировать другие данные
    /*
    cout << "Введите количество строк (N) и столбцов (M): ";
    cin >> N >> M;
    */

    vector<vector<int>> grid(N, vector<int>(M));
    
    // Заполняем матрицу примером из условия
    grid = {
        {2, -3, 2, 3},
        {10, 2, 2, 2},
        {-3, 20, 2, 2}
    };

    /*
    // Ввод с клавиатуры
    cout << "Введите значения матрицы:" << endl;
    for(int i = 0; i < N; ++i) {
        for(int j = 0; j < M; ++j) {
            cin >> grid[i][j];
        }
    }
    */

    // dp[i][j] будет хранить максимальную сумму баллов до клетки (i, j)
    // parent[i][j] будет хранить направление, откуда мы пришли: 'U' (сверху/up) или 'L' (слева/left)
    vector<vector<long long>> dp(N, vector<long long>(M, LLONG_MIN));
    vector<vector<char>> parent(N, vector<char>(M, ' '));

    // Инициализация старта
    dp[0][0] = grid[0][0];

    // Заполнение первой строки (можно прийти только слева)
    for (int j = 1; j < M; ++j) {
        dp[0][j] = dp[0][j-1] + grid[0][j];
        parent[0][j] = 'L';
    }

    // Заполнение первого столбца (можно прийти только сверху)
    for (int i = 1; i < N; ++i) {
        dp[i][0] = dp[i-1][0] + grid[i][0];
        parent[i][0] = 'U';
    }

    // Заполнение остальной части матрицы
    for (int i = 1; i < N; ++i) {
        for (int j = 1; j < M; ++j) {
            if (dp[i-1][j] > dp[i][j-1]) {
                dp[i][j] = dp[i-1][j] + grid[i][j];
                parent[i][j] = 'U';
            } else {
                dp[i][j] = dp[i][j-1] + grid[i][j];
                parent[i][j] = 'L';
            }
        }
    }

    // Восстановление пути
    vector<pair<int, int>> path;
    int r = N - 1;
    int c = M - 1;
    
    path.push_back({r, c});

    while (r != 0 || c != 0) {
        if (parent[r][c] == 'U') {
            r--;
        } else { // 'L'
            c--;
        }
        path.push_back({r, c});
    }

    // Путь восстановлен от конца к началу, разворачиваем его
    reverse(path.begin(), path.end());

    // Вывод результата
    cout << "Максимальная сумма баллов: " << dp[N-1][M-1] << endl;
    cout << "Маршрут (координаты строка столбец):" << endl;
    for (const auto& p : path) {
        cout << p.first << " " << p.second << endl;
    }
    cout << endl;
}

